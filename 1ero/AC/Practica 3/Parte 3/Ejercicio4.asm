EOI EQU 20H
IMR EQU 21H
INT0 EQU 24H

F10 EQU 10

PA EQU 30H
PB EQU 31H
CA EQU 32H
CB EQU 33H

ORG 40

IP_F10 DW RUT_F10

ORG 1000H

STR DB "PRESIONE F10 PARA COMENZAR"
PRESIONO DB 0
NUMEROS DB ?

ORG 2000H

CLI
MOV AL, 11111110B
OUT IMR, AL
MOV AL, F10
OUT INT0, AL
MOV BX, OFFSET STR
MOV AL, OFFSET NUMEROS - OFFSET STR
INT 7
STI

LOOP: CMP PRESIONO,1
JNZ LOOP

MOV CL, 10
MOV BX, OFFSET NUMEROS

LEER: INT 6
INC BX
DEC CL
JNZ LEER

MOV CL, 5
MOV BX, OFFSET NUMEROS + 8

APILAR: MOV AX, [BX]
PUSH AX
SUB BX, 2
DEC CL
JNZ APILAR

SIG:
CALL CONF_PIO
CALL IMPRIMIR

MOV CL, 5
DESAPILAR: POP AX
DEC CL
JNZ DESAPILAR

HLT

ORG 3000H

RUT_F10: PUSH AX

MOV PRESIONO, 1

MOV AL, 0FFH
OUT IMR, AL

MOV AL, EOI
OUT EOI, AL
POP AX

IRET

CONF_PIO: PUSH AX

MOV AL, 0
OUT CB, AL
MOV AL, 11111101B
OUT CA, AL

POP AX

RET

IMPRIMIR: PUSH BX
PUSH AX
PUSH CX

MOV BX, SP
ADD BX, 8

MOV CL, 10

ESPERAR: IN AL, PA
AND AL, 00000001B
JNZ ESPERAR

MOV AL, [BX]
OUT PB, AL

POLL: IN AL, PA
OR AL, 00000010B
OUT PA, AL
IN AL, PA
AND AL, 11111101B
OUT PA, AL

INC BX
DEC CL
JNZ ESPERAR

POP CX
POP AX
POP BX

RET

END