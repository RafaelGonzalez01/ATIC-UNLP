EOI EQU 20H
IMR EQU 21H
INT0 EQU 24H
F10 EQU 10

DATO EQU 40H
ESTADO EQU 41H

ORG 40

IP_F10 DW RUT_F10

ORG 1000H

STR DB "INGRESE UN NUMERO DEL 1 AL 9"
NUM DB ?
UNO DB "1"
NUEVE DB "9"
CERO DB "0"
TERMINO DB 0

ORG 2000H

CALL LEER_DIGITO

CLI
MOV AL, 11111110B
OUT IMR, AL
MOV AL, F10
OUT INT0, AL
STI

LOOP: CMP TERMINO, 1
JNZ LOOP

MOV BX, OFFSET NUM
MOV AL, [BX]
MOV AH, 0
PUSH AX

CALL DESCENDER

HLT

ORG 3000H

LEER_DIGITO:
PUSH BX
PUSH CX

MOV BX, OFFSET STR
MOV AL, OFFSET NUM - OFFSET STR
INT 7

MOV BX, OFFSET NUM
ERROR: INT 6
MOV CL, [BX]
CMP CL, UNO
JC ERROR
MOV CH, NUEVE
INC CH
CMP CL, CH
JNC ERROR

POP CX
POP BX
RET

RUT_F10:
PUSH AX

MOV TERMINO, 1

MOV AL, 0FFH
OUT IMR, AL
MOV AL, EOI
OUT EOI, AL
POP AX
IRET

DESCENDER:
PUSH BX
PUSH AX

MOV BX, SP
ADD BX, 6
MOV AH, [BX]

ESPERAR: IN AL, ESTADO
AND AL, 00000001B
JNZ ESPERAR

MOV AL, AH
OUT DATO, AL

DEC AH
CMP AH, CERO
JNC ESPERAR

POP AX
POP BX
RET

END