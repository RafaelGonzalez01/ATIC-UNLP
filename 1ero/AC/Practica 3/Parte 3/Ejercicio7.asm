EOI EQU 20H
IMR EQU 21H
INT0 EQU 24H
INT1 EQU 25H

CONT EQU 10H
COMP EQU 11H
TIMER EQU 10

F10 EQU 15

PA EQU 30H
PB EQU 31H
CA EQU 32H
CB EQU 33H

ORG 40
IP_TIMER DW RUT_TIMER

ORG 60

IP_F10 DW RUT_F10

ORG 1000H

STR DB "Hola!"
CERO DB "0"
TERMINO DB 0

ORG 2000H

CALL CONF_PIO
MOV BX, OFFSET STR

CLI
MOV AL, 11111100B
OUT IMR, AL
MOV AL, F10
OUT INT0, AL
MOV AL, TIMER
OUT INT1, AL
MOV AL, 0
OUT CONT, AL
MOV AL, 5
OUT COMP, AL
MOV AL, [BX]
OUT PB, AL
INC BX
STI

LAZO: CMP TERMINO, 2
JNZ LAZO

HLT

ORG 3000H

CONF_PIO:
PUSH AX
MOV AL, 0
OUT CB, AL
POP AX
RET

RUT_TIMER:
PUSH AX
PUSH CX

CMP TERMINO, 1
JZ FINALIZAR

MOV CX, OFFSET CERO
SUB CX, BX

MOV AL, [BX]
OUT PB, AL

MOV AL, 0
OUT CONT, AL

INC BX
DEC CX
JNZ FIN_T
MOV TERMINO, 1
JMP FIN_T

FINALIZAR: MOV TERMINO, 2
MOV AL, 0
OUT PB, AL
MOV AL, 0FFH
OUT IMR, AL

FIN_T: MOV AL, EOI
OUT EOI, AL
POP CX
POP AX
IRET

RUT_F10: PUSH AX

MOV TERMINO, 2
MOV AL, 0FFH
OUT IMR , AL

MOV AL, EOI
OUT EOI, AL
POP AX
IRET



END