EOI EQU 20H
IMR EQU 21H
INT0 EQU 24H

F10 EQU 10

ORG 40

IP_F10 DW RUT_F10

ORG 1000H

CERO DB "0"
NUEVE DB "9"
NUM DB "0"
TERMINO DB 0

ORG 2000H

CLI
MOV AL, 11111110B
OUT IMR, AL
MOV AL, F10
OUT INT0, AL
MOV BX, OFFSET NUM
STI

INCREMENTAR: CMP TERMINO, 1
JZ FIN
MOV AL, [BX]
INC AL
MOV [BX], AL
CMP AL, NUEVE
JNZ INCREMENTAR
DECREMENTAR: CMP TERMINO, 1
JZ FIN
MOV AL, [BX]
DEC AL
MOV [BX], AL
CMP AL, CERO
JZ INCREMENTAR
JMP DECREMENTAR

FIN: HLT

ORG 3000H

RUT_F10: PUSH BX
PUSH AX

MOV BX, OFFSET NUM
MOV AL, 1
INT 7

MOV TERMINO, 1

MOV AL, EOI
OUT EOI, AL

POP AX
POP BX
IRET

END
