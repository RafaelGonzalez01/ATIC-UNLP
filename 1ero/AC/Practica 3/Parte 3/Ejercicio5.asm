EOI EQU 20H
IMR EQU 21H
INT1 EQU 25H

CONT EQU 10H
COMP EQU 11H

PA EQU 30H
PB EQU 31H
CA EQU 32H
CB EQU 33H

TIMER EQU 10

ORG 40

IP_TIMER DW RUT_TIMER

ORG 1000H

PRENDIDAS DB 0
ESTADO DB ?

ORG 2000H

CALL CONF_PIO
CLI
CALL CONF_IMR
STI

LAZO: IN AL, PA
MOV BX, OFFSET ESTADO
MOV [BX], AL
PUSH BX
CALL LUCES12
POP BX
JMP LAZO

HLT

ORG 3000H

LUCES12:
PUSH AX
PUSH BX

MOV BX, SP
ADD BX, 6

MOV AX, [BX]
MOV BX, AX

MOV AL, [BX]

AND AL, 10000000B
JZ FIN
CMP PRENDIDAS, 1
JZ FIN

MOV AL, 0
OUT CONT, AL
MOV AL, 12
OUT COMP, AL

MOV AL, 11111111B
OUT PB, AL
MOV PRENDIDAS, 1

FIN: POP BX
POP AX

RET
 
CONF_IMR:
PUSH AX
MOV AL, 11111101B
OUT IMR, AL
MOV AL, TIMER
OUT INT1, AL
MOV AL, 0
OUT CONT, AL
MOV AL, 0
OUT COMP, AL
POP AX
RET

CONF_PIO:
PUSH AX

MOV AL, 0H
OUT CB, AL
MOV AL, 0FFH
OUT CA, AL

POP AX

RET

RUT_TIMER:
PUSH AX

MOV AL, 0
OUT PB, AL
MOV PRENDIDAS, 0

MOV AL, EOI
OUT EOI, AL

POP AX

IRET

END
