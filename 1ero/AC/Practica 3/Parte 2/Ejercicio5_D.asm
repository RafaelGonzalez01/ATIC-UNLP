IMR EQU 21h
INT1 EQU 25h
TIMER EQU 10
CONT EQU 10H
COMP EQU 11H

ORG 28H
IP_TIMER DW RUT_TIMER

ORG 1000H

MSJ DB "VAMOS LAS INTERRUPCIONES!"
FIN DB 1

ORG 2000h

CLI
MOV AL, 11111101B
OUT IMR,AL
MOV AL, TIMER
OUT INT1,AL
MOV AL, 0
OUT CONT, AL
MOV AL, 1
OUT COMP, AL
STI

LOOP: CMP FIN, 255
JNZ LOOP

HLT

ORG 3000H

RUT_TIMER:
PUSH AX
PUSH BX

MOV BX, OFFSET MSJ
MOV AL, OFFSET FIN - OFFSET MSJ
INT 7

INC FIN
CMP FIN, 255
JZ FINSUB

MOV AL, FIN
OUT COMP,AL
MOV AL, 0
OUT CONT, AL
JMP CONTINUAR

FINSUB:MOV AL, 0FFH
OUT IMR, AL

CONTINUAR: POP BX
POP AX

MOV AL, EOI
OUT EOI, AL
IRET

