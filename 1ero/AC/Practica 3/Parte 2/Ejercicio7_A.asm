EOI EQU 20H
IMR EQU 21H
INT2 EQU 26H

HAND EQU 10
DATOS EQU 40H
ESTADO EQU 41H

ORG 40

IP_HAND DW RUT_HAND

ORG 1000H
MSJ DB "UNIVERSIDAD NACIONAL DE LA PLATA"
FIN DB ?

ORG 2000H

MOV DL, OFFSET FIN - OFFSET MSJ
MOV BX, OFFSET MSJ

CLI
MOV AL, 11111011B
OUT IMR , AL
MOV AL, HAND
OUT INT2, AL
MOV AL, 80H
OUT ESTADO, AL
STI

LOOP: JMP LOOP

HLT

ORG 3000H

RUT_HAND: PUSH AX

IN AL, ESTADO
AND AL, 00000001
JNZ FIN_H

CMP DL, 0
JZ FIN_H

MOV AL, [BX]
OUT DATOS, AL
INC BX
DEC DL

FIN_H: POP AX

MOV AL, EOI
OUT EOI, AL

IRET

END