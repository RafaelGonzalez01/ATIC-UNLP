IMR EQU 21H

INT2 EQU 26H

DATO EQU 40H
ESTADO EQU 41H

HAND EQU 10

ORG 40

IP_HAND DW RUT_HAND

ORG 1000H

STR DB ?

ORG 2000H

MOV CL, 10
MOV BX, OFFSET STR

LOOP1: INT 6
INC BX
DEC CL
JNZ LOOP1

CLI
MOV AL, 11111011B
OUT IMR, AL
MOV AL, HAND
OUT INT2, AL
MOV AL, 80H
OUT ESTADO, AL
MOV BX, OFFSET STR
STI

