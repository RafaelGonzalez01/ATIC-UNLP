EOI EQU 20H
IMR EQU 21H

INT0 EQU 24H
INT1 EQU 25H

F10 EQU 10

TIMER EQU 15
CONT EQU 10H
COMP EQU 11H

ORG 40
DW IP_F10

ORG 60
DW IP_TIMER

ORG 1000H

NUM DB "9"
CERO DB "0"
NUEVE DB "9"
CONTANDO DB 1

ORG 2000H

CLI
MOV AL, 11111100B
OUT IMR, AL

MOV AL, F10
OUT INT0, AL

MOV AL, TIMER
OUT INT1, AL
MOV AL, 0
OUT CONT, AL
MOV AL, 1
OUT COMP, AL
STI

LOOP: JMP LOOP

INT 0

ORG 3000H

IP_F10: PUSH AX
PUSH BX
MOV BX, OFFSET NUM
CMP CONTANDO, 0
JNZ PARAR
MOV AH, [BX]
CMP AH,CERO - 1
JNZ REANUDAR
MOV AH, NUEVE
MOV [BX], AH

REANUDAR: MOV AL, 11111100B
OUT IMR, AL
MOV CONTANDO, 1
JMP FIN_F10

PARAR: MOV AL, 11111110B
OUT IMR, AL
MOV CONTANDO, 0

FIN_F10: POP AX
POP BX
MOV AL, EOI
OUT EOI, AL

IRET

IP_TIMER: PUSH BX
PUSH AX
PUSH CX

CMP CONTANDO, 0
JZ FIN_T

MOV BX, OFFSET NUM
MOV AL, 1
MOV CL, [BX]
MOV CH, CL

INT 7
DEC CH
MOV [BX],CH
CMP CL, CERO
JNZ FIN_T

MOV AL, 11111110B
OUT IMR, AL

MOV CONTANDO, 0

FIN_T: MOV AL, 0
OUT CONT, AL
POP CX
POP AX
POP BX

MOV AL, EOI
OUT EOI, AL

IRET

END