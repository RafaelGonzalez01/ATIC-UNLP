EOI EQU 20H
IMR EQU 21H
INT0 EQU 24H
INT2 EQU 26H

DATO EQU 40H
ESTADO EQU 41H

HAND EQU 10

F10 EQU 15

ORG 40

IP_HAND DW RUT_HAND

ORG 60

IP_F10 DW RUT_F10

ORG 1000H

STR DB ?

ORG 2000H

MOV CL, 10
MOV BX, OFFSET STR

LOOP1: INT 6
INC BX
DEC CL
JNZ LOOP1

CLI
MOV AL, 11111010B
OUT IMR, AL
MOV AL, HAND
OUT INT2, AL
MOV AL, 80H
OUT ESTADO, AL
MOV BX, OFFSET STR
MOV AL, F10
OUT INT0, AL
STI

LOOP2: JMP LOOP2

ORG 3000H

RUT_HAND:
PUSH AX

CMP CL, 10
JZ FIN_H
MOV AL, [BX]
OUT DATO, AL
INC BX
INC CL

FIN_H: MOV AL, EOI
OUT EOI,AL

POP AX

IRET

RUT_F10:
PUSH AX

MOV AL, 0FFH
OUT IMR, AL

MOV AL, EOI
OUT EOI,AL

POP AX

IRET

END